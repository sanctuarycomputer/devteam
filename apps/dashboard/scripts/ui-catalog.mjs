#!/usr/bin/env node
// apps-src@2 (APPS.md): the design-system page's catalog, and the duplicates scan.
//   node scripts/ui-catalog.mjs [--ui <dir>] [--out <file>]
//     writes the catalog (default src/views/design-system/catalog.gen.ts, gitignored) importing every
//     <name>.specimens.tsx under the ui folder (default src/shared/ui/). The build runs it before
//     `next build`, and predev before `next dev`. It writes only when the text changes.
//   node scripts/ui-catalog.mjs --duplicates [--apps <dir>]
//     prints each class defined in the apps' CSS that is the className of a JSX tree's outermost element
//     in two or more view folders (src/views/<view>/, src/shared/<module>/ but ui/) of either app.
// Exit 0 done; 1 refused (a component and its specimens don't pair, a file the folder doesn't allow);
// 2 usage. Node 18+, built-ins only: it runs before anything is installed.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const APP = path.join(here, '..');
const REPO = path.join(APP, '..', '..');
const posix = (p) => p.split(path.sep).join('/');
const rel = (p) => posix(path.relative(REPO, p));

export class Refused extends Error {}
const NAME = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

// ---- the catalog ----

// The ui folder's components: [{ name, file, specimens, css, props }], by name. A missing folder is none.
export function components(ui) {
  if (!fs.existsSync(ui)) return [];
  const by = new Map();
  const at = (name) => by.get(name) ?? by.set(name, { name }).get(name);
  for (const e of fs.readdirSync(ui, { withFileTypes: true })) {
    const m = /^(.+?)(\.specimens\.tsx|\.tsx|\.css)$/.exec(e.name);
    if (!e.isFile() || !m || !NAME.test(m[1])) throw new Refused(`${rel(path.join(ui, e.name))}: the ui folder holds only <name>.tsx, <name>.specimens.tsx and <name>.css, <name> in kebab-case`);
    const kind = { '.tsx': 'file', '.specimens.tsx': 'specimens', '.css': 'css' }[m[2]];
    at(m[1])[kind] = path.join(ui, e.name);
  }
  const list = [...by.values()].sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const c of list) {
    if (!c.file) throw new Refused(`${rel(c.specimens ?? c.css)}: no ${c.name}.tsx beside it`);
    if (!c.specimens) throw new Refused(`${rel(c.file)}: no ${c.name}.specimens.tsx beside it (every component has its specimens)`);
    const s = strip(fs.readFileSync(c.specimens, 'utf8'));
    if (!/\bexport\s+const\s+specimens\b/.test(s)) throw new Refused(`${rel(c.specimens)}: it doesn't export const specimens`);
    if (!/\bexport\s+const\s+specimens\b[^=]*=\s*\[\s*\{/.test(s) || !/\btitle\s*:/.test(s) || !/\brender\s*[:(]/.test(s)) throw new Refused(`${rel(c.specimens)}: no specimen in it (each is { title, note?, render })`);
    c.props = propsOf(fs.readFileSync(c.file, 'utf8'), c.name);
  }
  return list;
}

// The props' names: the members of `export type <Pascal>Props = { … }` or `export interface <Pascal>Props { … }`.
export function propsOf(src, name) {
  const pascal = name.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
  const s = strip(src);
  const m = new RegExp(`\\bexport\\s+(?:type\\s+${pascal}Props\\s*=|interface\\s+${pascal}Props\\b[^{]*)\\s*\\{`).exec(s);
  if (!m) return [];
  let depth = 0, i = m.index + m[0].length - 1, part = '';
  const parts = [];
  for (; i < s.length; i++) {
    const c = s[i];
    if ('{([<'.includes(c)) { depth++; if (depth === 1) continue; }
    if ('})]>'.includes(c) && !(c === '>' && s[i - 1] === '=')) { depth--; if (depth === 0) break; }
    if (depth === 1 && (c === ';' || c === ',' || c === '\n')) { parts.push(part); part = ''; } else part += c;
  }
  parts.push(part);
  return parts.map((p) => /^\s*(?:readonly\s+)?([A-Za-z_$][\w$]*)\s*\??\s*:/.exec(p)?.[1]).filter(Boolean);
}

// Comments and string bodies blanked (their length kept), for the regexes above: a `title:` in a string or
// a comment is no specimen. A quote's string ends at its line's end (an apostrophe in JSX text blanks at
// most the rest of its line).
function strip(src) {
  return src.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*|'(?:\\.|[^'\\\n])*'|"(?:\\.|[^"\\\n])*"|`(?:\\.|[^`\\])*`/g, (c) => {
    if (c[0] === '/') return c.replace(/[^\n]/g, ' ');
    return c[0] + c.slice(1, -1).replace(/[^\n]/g, ' ') + c.slice(-1);
  });
}

export function catalogText(list, out) {
  const from = (f) => { const r = posix(path.relative(path.dirname(out), f)).replace(/\.tsx$/, ''); return r.startsWith('.') ? r : `./${r}`; };
  const lines = [
    '// Generated by apps/dashboard/scripts/ui-catalog.mjs from the ui folder (apps-src@2). Do not edit: the build and',
    '// predev write it again. Each entry is a component of src/shared/ui/ with its specimens.',
    "import type { Specimen } from './specimen';",
    ...list.map((c, i) => `import { specimens as s${i} } from '${from(c.specimens)}';`),
    '',
    'export type CatalogEntry = { name: string; file: string; props: string[]; specimens: Specimen[] };',
    '',
    'export const catalog: CatalogEntry[] = [',
    ...list.map((c, i) => `  { name: ${JSON.stringify(c.name)}, file: ${JSON.stringify(rel(c.file))}, props: ${JSON.stringify(c.props)}, specimens: s${i} },`),
    '];',
    '',
  ];
  return lines.join('\n');
}

export function writeCatalog(ui, out) {
  const text = catalogText(components(ui), out);
  if (fs.existsSync(out) && fs.readFileSync(out, 'utf8') === text) return false;
  fs.mkdirSync(path.dirname(out), { recursive: true });
  const tmp = `${out}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, text);
  fs.renameSync(tmp, out);
  return true;
}

// ---- the duplicates scan ----

// Each JSX tree's outermost elements in a .tsx file: [{ tag, classes }], classes from a static className
// ("a b", {'a b'}) only. A tree's outermost element is the one no other JSX element holds; a fragment's
// (<>…</>) are its own direct child elements. A scanner, not a parser: code is read for its strings,
// template literals, regular expressions, comments and braces, and JSX for its tags, attributes and
// children, so JSX text (an apostrophe) and JSX inside a child's braces are read as such.
export function outermost(src) {
  const out = [];
  const n = src.length;
  // a '<' or '/' after one of these starts an expression (JSX, a regular expression), not an operator
  const START = /^(?:|[(,=?:[{}&|!;+\-*%~^]|=>|return|default|yield|await|case|in|of|typeof|void)$/;
  // a string or template literal at j: the index after it
  const str = (j, record) => {
    const q = src[j];
    for (j++; j < n; j++) {
      if (src[j] === '\\') { j++; continue; }
      if (src[j] === q) return j + 1;
      if (q === '`' && src[j] === '$' && src[j + 1] === '{') j = code(j + 2, record) - 1;
    }
    return n;
  };
  // a regular expression literal at j: the index after its flags
  const regex = (j) => {
    let inClass = false;
    for (j++; j < n; j++) {
      const c = src[j];
      if (c === '\\') { j++; continue; }
      if (c === '\n') return j;
      if (inClass) { if (c === ']') inClass = false; continue; }
      if (c === '[') inClass = true;
      else if (c === '/') { j++; while (j < n && /[a-z]/i.test(src[j])) j++; return j; }
    }
    return n;
  };
  // code from j to the '}' that closes it (or the end): the index after that '}'
  function code(j, record) {
    let prev = '';
    while (j < n) {
      const c = src[j];
      if (c === '}') return j + 1;
      if (c === '"' || c === "'" || c === '`') { j = str(j, record); prev = 'x'; continue; }
      if (c === '/' && src[j + 1] === '/') { const e = src.indexOf('\n', j); j = e < 0 ? n : e; continue; }
      if (c === '/' && src[j + 1] === '*') { const e = src.indexOf('*/', j + 2); j = e < 0 ? n : e + 2; continue; }
      if (/\s/.test(c)) { j++; continue; }
      if (c === '/' && START.test(prev)) { j = regex(j); prev = 'x'; continue; }
      if (c === '{') { j = code(j + 1, record); prev = '}'; continue; }
      if (c === '<' && START.test(prev) && /[A-Za-z>]/.test(src[j + 1] ?? '')) { j = element(j, record); prev = 'x'; continue; }
      const w = /^[A-Za-z_$][\w$]*/.exec(src.slice(j, j + 64));
      if (w) { prev = w[0]; j += w[0].length; continue; }
      if (c === '=' && src[j + 1] === '>') { prev = '=>'; j += 2; continue; }
      prev = c;
      j++;
    }
    return n;
  }
  // a JSX element at j: the index after its end. record (when given) takes it, as an outermost element
  function element(j, record) {
    const m = /^<\s*([A-Za-z][\w.:-]*)?/.exec(src.slice(j, j + 200));
    const tag = m[1] ?? '';
    j += m[0].length;
    let classes = null, selfClosing = false;
    while (j < n) {
      const c = src[j];
      if (/\s/.test(c)) { j++; continue; }
      if (c === '/' && src[j + 1] === '>') { selfClosing = true; j += 2; break; }
      if (c === '>') { j++; break; }
      if (c === '{') { j = code(j + 1, null); continue; }
      const a = /^([A-Za-z_][\w:.-]*)\s*(=\s*)?/.exec(src.slice(j, j + 200));
      if (!a) { j++; continue; }
      j += a[0].length;
      if (!a[2]) continue;
      if (src[j] === '"' || src[j] === "'") {
        const end = src.indexOf(src[j], j + 1);
        if (a[1] === 'className') classes = src.slice(j + 1, end);
        j = end < 0 ? n : end + 1;
      } else if (src[j] === '{') {
        const end = code(j + 1, null);
        const inner = /^\{\s*(["'])([^"'`\\]*)\1\s*\}$/.exec(src.slice(j, end));
        if (a[1] === 'className' && inner) classes = inner[2];
        j = end;
      }
    }
    if (record && tag) record({ tag, classes: classes ? classes.split(/\s+/).filter(Boolean) : [] });
    // a fragment's own child elements are outermost too
    return selfClosing ? j : children(j, tag ? null : record);
  }
  // an element's children up to its closing tag: the index after it
  function children(j, record) {
    while (j < n) {
      const c = src[j];
      if (c === '{') { j = code(j + 1, null); continue; }
      if (c === '<') {
        if (src[j + 1] === '/') { const e = src.indexOf('>', j); return e < 0 ? n : e + 1; }
        j = element(j, record);
        continue;
      }
      j++;
    }
    return n;
  }
  // the file: code that no '}' closes (one that does, unbalanced, ends nothing: go on after it)
  for (let j = 0; j < n;) j = code(j, (e) => out.push(e));
  return out;
}

// Every class a stylesheet defines: each .name in a selector (declarations and comments set aside).
export function cssClasses(css) {
  const set = new Set();
  const s = css.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/\{[^{}]*\}/g, '{}');
  for (const m of s.matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) set.add(m[1]);
  return set;
}

const walk = (d) => (fs.existsSync(d) ? fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(path.join(d, e.name)) : e.isFile() ? [path.join(d, e.name)] : [])) : []);

// The scan over an apps folder: [{ class, files }], by class.
export function duplicates(apps) {
  const appsList = fs.existsSync(apps) ? fs.readdirSync(apps, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort() : [];
  const defined = new Set();
  const seen = new Map(); // class → Map(folder → Set(file))
  for (const a of appsList) {
    const src = path.join(apps, a, 'src');
    for (const f of walk(src).filter((f) => f.endsWith('.css'))) for (const c of cssClasses(fs.readFileSync(f, 'utf8'))) defined.add(c);
    for (const f of walk(src).filter((f) => f.endsWith('.tsx'))) {
      const parts = posix(path.relative(src, f)).split('/');
      let folder = null;
      if (parts[0] === 'views' && parts.length > 2) folder = `${a}/src/views/${parts[1]}`;
      else if (parts[0] === 'shared' && parts[1] !== 'ui') folder = `${a}/src/shared/${parts.length > 2 ? parts[1] : parts[1].replace(/\.tsx$/, '')}`;
      if (!folder) continue;
      for (const el of outermost(fs.readFileSync(f, 'utf8'))) for (const c of el.classes) {
        const by = seen.get(c) ?? seen.set(c, new Map()).get(c);
        (by.get(folder) ?? by.set(folder, new Set()).get(folder)).add(rel(f));
      }
    }
  }
  return [...seen].filter(([c, by]) => defined.has(c) && by.size >= 2).map(([c, by]) => ({ class: c, files: [...by.values()].flatMap((s) => [...s]).sort() })).sort((x, y) => (x.class < y.class ? -1 : x.class > y.class ? 1 : 0));
}

// ---- the command ----

function main(argv) {
  const o = { ui: path.join(APP, 'src', 'shared', 'ui'), out: path.join(APP, 'src', 'views', 'design-system', 'catalog.gen.ts'), apps: path.join(APP, '..'), duplicates: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--duplicates') o.duplicates = true;
    else if (['--ui', '--out', '--apps'].includes(a) && argv[i + 1] && !argv[i + 1].startsWith('--')) o[a.slice(2)] = path.resolve(argv[++i]);
    else { process.stderr.write(`ui-catalog: unknown or incomplete option ${a}\nusage: ui-catalog.mjs [--ui <dir>] [--out <file>] | --duplicates [--apps <dir>]\n`); return 2; }
  }
  try {
    if (o.duplicates) {
      const d = duplicates(o.apps);
      process.stdout.write(d.length ? d.map((x) => `.${x.class}: ${x.files.join(', ')}\n`).join('') : 'No duplicates.\n');
      return 0;
    }
    const wrote = writeCatalog(o.ui, o.out);
    process.stdout.write(`ui-catalog: ${rel(o.out)} ${wrote ? 'written' : 'unchanged'} (${components(o.ui).length} components)\n`);
    return 0;
  } catch (e) {
    if (e instanceof Refused) { process.stderr.write(`ui-catalog: refused: ${e.message}\n`); return 1; }
    throw e;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));
